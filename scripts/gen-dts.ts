// Generates dist/core/index.{js,d.ts} from src/helpers.c, the single source of truth for
// the module boundary: every `API` function becomes a typed export, every SNY_CONST* a
// constant. Usage: bun scripts/gen-dts.ts

const root = new URL("../", import.meta.url).pathname;
const src = await Bun.file(`${root}src/helpers.c`).text();
const out = `${root}dist/core/`;

function tsType(cType: string): string {
  if (cType.includes("*")) return "Ptr";
  if (/\bu?int64_t\b/.test(cType)) return "bigint";
  return cType.trim() === "void" ? "void" : "number";
}

const fns: string[] = [];

for (const m of src.matchAll(/^API\s+(?<ret>.+?)\b(?<name>sny_\w+)\((?<params>[^)]*)\)/gm)) {
  const { ret = "", name = "", params = "" } = m.groups ?? {};
  const args =
    params.trim() === "void"
      ? []
      : params.split(",").map((param) => {
          const { type = "", arg = "" } =
            /^(?<type>.*?)(?<arg>\w+)$/.exec(param.trim())?.groups ?? {};
          return `${arg}: ${tsType(type)}`;
        });
  fns.push(`  _${name}(${args.join(", ")}): ${tsType(ret)};`);
}

const consts: string[] = [];

for (const m of src.matchAll(/^SNY_CONST(?<wide>64)?\((?<name>.+?), (?<value>.+?)\)$/gm)) {
  const { wide, name = "", value = "" } = m.groups ?? {};
  const id = name.replace(/\((\w+)\)/, "_$1"); // AVERROR(EAGAIN) -> AVERROR_EAGAIN
  const literal = value === "INT64_MIN" ? "-0x8000000000000000n" : `${value}n`;
  consts.push(`export const ${id} = ${wide ? literal : value};`);
}

const header = "// Generated by scripts/gen-dts.ts from src/helpers.c. Do not edit.\n";

await Bun.write(
  `${out}index.js`,
  `${header}export { default as createCore } from "./core.js";\n${consts.join("\n")}\n`,
);

await Bun.write(
  `${out}index.d.ts`,
  `${header}
/** A pointer into the module's WASM memory. */
export type Ptr = number;

export interface CoreModule {
  readonly HEAPU8: Uint8Array;
  readonly HEAP32: Int32Array;
  UTF8ToString(ptr: Ptr, maxBytesToRead?: number): string;
  stringToNewUTF8(s: string): Ptr;
  _malloc(size: number): Ptr;
  _free(ptr: Ptr): void;

  /** Read hook for input \`io\`: copy up to \`size\` bytes to \`buf\`; return bytes read, 0 at end, or a negative AVERROR. */
  snyRead(io: number, buf: Ptr, size: number): number;
  /** Seek hook for input \`io\` (whence: 0 set, 1 cur, 2 end, AVSEEK_SIZE): return the new position or size, or a negative AVERROR. */
  snySeek(io: number, offset: bigint, whence: number): bigint;

${fns.join("\n")}
}

export interface CoreOptions {
  locateFile?(path: string, prefix: string): string;
  wasmBinary?: ArrayBuffer;
}

export function createCore(options?: CoreOptions): Promise<CoreModule>;

${consts.map((c) => c.replace(/^export const (\w+) = .*$/, (_, n) => `export declare const ${n}: ${c.endsWith("n;") ? "bigint" : "number"};`)).join("\n")}
`,
);

console.log(`${fns.length} functions, ${consts.length} constants`);
