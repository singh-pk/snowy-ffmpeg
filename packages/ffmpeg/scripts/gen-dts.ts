// Generates dist/<module>/index.{js,d.ts} from the module's API files in src/ (listed in
// src/sny.h), the single source of truth for the module boundary: every `API` function
// becomes a typed export, every SNY_CONST* a constant. Usage: bun scripts/gen-dts.ts

const root = new URL("../", import.meta.url).pathname;

const modules = [
  {
    dir: "core",
    factory: "createCore",
    iface: "Core",
    files: ["common", "demux", "decode", "audio"],
  },
  {
    dir: "audio-ext",
    factory: "createAudioExt",
    iface: "AudioExt",
    files: ["common", "decode", "audio"],
  },
  { dir: "video", factory: "createVideo", iface: "Video", files: ["common", "decode", "video"] },
  {
    dir: "video-ext",
    factory: "createVideoExt",
    iface: "VideoExt",
    files: ["common", "decode", "video"],
  },
];

function tsType(cType: string): string {
  if (cType.includes("*")) return "Ptr";
  if (/\bu?int64_t\b/.test(cType)) return "bigint";
  return cType.trim() === "void" ? "void" : "number";
}

async function generate({ dir, factory, iface, files }: (typeof modules)[number]) {
  const sources = await Promise.all(files.map((f) => Bun.file(`${root}src/${f}.c`).text()));
  const src = sources.join("\n");
  const out = `${root}dist/${dir}/`;
  const fns: string[] = [];

  for (const m of src.matchAll(/^API\s+(?<ret>.+?)\b(?<name>sny_\w+)\((?<params>[^)]*)\)/gm)) {
    const { ret = "", name = "", params = "" } = m.groups ?? {};
    const args =
      params.trim() === "void"
        ? []
        : params.split(",").map((param) => {
            const { type = "", arg = "" } =
              /^(?<type>.*?)(?<arg>\w+)$/.exec(param.trim())?.groups ?? {};
            return `${arg}: ${tsType(type)}`;
          });
    fns.push(`  _${name}(${args.join(", ")}): ${tsType(ret)};`);
  }

  const consts: string[] = [];

  for (const m of src.matchAll(/^SNY_CONST(?<wide>64)?\((?<name>.+?), (?<value>.+?)\)$/gm)) {
    const { wide, name = "", value = "" } = m.groups ?? {};
    const id = name.replace(/\((\w+)\)/, "_$1"); // AVERROR(EAGAIN) -> AVERROR_EAGAIN
    const literal = value === "INT64_MIN" ? "-0x8000000000000000n" : `${value}n`;
    consts.push(`export const ${id} = ${wide ? literal : value};`);
  }

  const from = files.map((f) => `src/${f}.c`).join(", ");
  const header = `// Generated by scripts/gen-dts.ts from ${from}. Do not edit.\n`;
  // The JavaScript I/O hooks of src/io.js, in modules that demux.
  const io = files.includes("demux")
    ? `
  /** Read hook for input \`io\`: copy up to \`size\` bytes to \`buf\`; return bytes read, 0 at end, or a negative AVERROR. */
  snyRead(io: number, buf: Ptr, size: number): number;
  /** Seek hook for input \`io\` (whence: 0 set, 1 cur, 2 end, AVSEEK_SIZE): return the new position or size, or a negative AVERROR. */
  snySeek(io: number, offset: bigint, whence: number): bigint;
`
    : "";

  await Bun.write(
    `${out}index.js`,
    `${header}export { default as ${factory} } from "./${dir}.js";\n${consts.join("\n")}\n`,
  );

  await Bun.write(
    `${out}index.d.ts`,
    `${header}
/** A pointer into the module's WASM memory. */
export type Ptr = number;

export interface ${iface}Module {
  readonly HEAPU8: Uint8Array;
  readonly HEAP32: Int32Array;
  readonly HEAPF32: Float32Array;
  UTF8ToString(ptr: Ptr, maxBytesToRead?: number): string;
  stringToNewUTF8(s: string): Ptr;
  _malloc(size: number): Ptr;
  _free(ptr: Ptr): void;
${io}
${fns.join("\n")}
}

export interface ${iface}Options {
  locateFile?(path: string, prefix: string): string;
  wasmBinary?: ArrayBuffer;
}

export function ${factory}(options?: ${iface}Options): Promise<${iface}Module>;

${consts.map((c) => c.replace(/^export const (\w+) = .*$/, (_, n) => `export declare const ${n}: ${c.endsWith("n;") ? "bigint" : "number"};`)).join("\n")}
`,
  );

  console.log(`${dir}: ${fns.length} functions, ${consts.length} constants`);
}

await Promise.all(modules.map(generate));
